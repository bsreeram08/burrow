/// Optional rich parts of a message (docs/phase1-protocol.md §1 and §3): a quoted reply, one
/// attachment, one link preview. Each `fromJson` is strict, like the rest of the store: exact keys,
/// exact types, the protocol's bounds, and a [FormatException] for anything else (the store turns it
/// into a deterministic `invalid` rejection). `toJson` omits absent optional keys, never writes null.

const maxAttachmentBytes = 25 * 1024 * 1024;
const maxThumbChars = 4096;
const maxReplyPreview = 140;
const attachmentKinds = {'image', 'video', 'audio', 'voice', 'file'};

final _uuid = RegExp(r'^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$', caseSensitive: false);
final _blobId = RegExp(r'^[A-Za-z0-9_-]{22}$');
final _b64u32 = RegExp(r'^[A-Za-z0-9_-]{43}$');
final _mime = RegExp(r'^[A-Za-z0-9.+-]{1,64}/[A-Za-z0-9.+-]{1,64}(\s*;\s*[A-Za-z0-9.+-]{1,32}=("[^"\\\x00-\x1f]{0,64}"|[A-Za-z0-9.+-]{1,64}))*$');
const _thumbPrefix = 'data:image/jpeg;base64,';

Never _bad(String what) => throw FormatException('Invalid $what');

Map<String, Object?> _exact(Object? json, Set<String> required, Set<String> optional, String what) {
  if (json is! Map) _bad(what);
  for (final key in json.keys) {
    if (key is! String || !(required.contains(key) || optional.contains(key))) _bad(what);
  }
  if (!required.every(json.containsKey)) _bad(what);
  // A present optional key must carry a value: absent keys are omitted, never null.
  if (json.values.any((v) => v == null)) _bad(what);
  return json.cast<String, Object?>();
}

String _string(Object? value, String what, {int min = 0, required int max}) {
  if (value is! String || value.length < min || value.length > max) _bad(what);
  return value;
}

/// A JPEG data URL of at most 4 KB whose payload is valid base64.
String? _thumb(Object? value) {
  if (value == null) return null;
  // Senders keep the whole data URL within 4096 characters; receivers accept up to 4 KB decoded, like the web client.
  if (value is! String || value.length > _thumbPrefix.length + 5464 || !value.startsWith(_thumbPrefix)) _bad('thumb');
  try {
    final bytes = base64.decode(value.substring(_thumbPrefix.length));
    if (bytes.isEmpty || bytes.length > 4096) _bad('thumb');
  } on FormatException {
    _bad('thumb');
  }
  return value;
}

/// Bidi, format and zero-width characters are removed from names on store and receive, exactly as the
/// web ChatStore does, so both clients hold identical records; a name left empty becomes 'file'.
final _invisibleInName = RegExp('[\u061C\u180E\u200B-\u200F\u202A-\u202E\u2060-\u2069\uFEFF]');
String _storedName(String name) {
  final clean = name.replaceAll(_invisibleInName, '');
  return clean.isEmpty ? 'file' : clean;
}

bool _sameJson(Object? a, Object? b) => jsonEncode(a) == jsonEncode(b);

/// `replyTo: {id, text}`. [text] is the sender's preview of the quoted message.
class ReplyTo {
  const ReplyTo({required this.id, required this.text});
  final String id;
  final String text;

  factory ReplyTo.fromJson(Object? json) {
    final m = _exact(json, const {'id', 'text'}, const {}, 'reply');
    final id = m['id'];
    if (id is! String || !_uuid.hasMatch(id)) _bad('reply');
    return ReplyTo(id: id.toLowerCase(), text: _string(m['text'], 'reply', max: maxReplyPreview));
  }

  /// A one-line preview of [text] cut to the protocol's 140 characters, whole graphemes only.
  factory ReplyTo.preview(String id, String text) {
    final line = text.replaceAll(RegExp(r'\s+'), ' ').trim();
    var out = '';
    for (final g in line.characters) {
      if (out.length + g.length > maxReplyPreview) break;
      out += g;
    }
    return ReplyTo(id: id.toLowerCase(), text: out);
  }

  Map<String, Object?> toJson() => {'id': id, 'text': text};
  @override
  bool operator ==(Object other) => other is ReplyTo && other.id == id && other.text == text;
  @override
  int get hashCode => Object.hash(id, text);
}

/// `link: {url, title?, description?, site?, thumb?}`, generated by the sender only.
class LinkPreview {
  const LinkPreview({required this.url, this.title, this.description, this.site, this.thumb});
  final String url;
  final String? title, description, site, thumb;

  static bool isHttpsUrl(String url) {
    if (url.length > 2048) return false;
    final uri = Uri.tryParse(url);
    return uri != null && uri.scheme == 'https' && uri.host.isNotEmpty && !url.contains(RegExp(r'\s'));
  }

  /// [text] is the message text the link must appear in.
  factory LinkPreview.fromJson(Object? json, String text) {
    final m = _exact(json, const {'url'}, const {'title', 'description', 'site', 'thumb'}, 'link');
    final url = _string(m['url'], 'link', min: 1, max: 2048);
    if (!isHttpsUrl(url) || !text.contains(url)) _bad('link');
    return LinkPreview(
      url: url,
      title: m['title'] == null ? null : _string(m['title'], 'link', max: 200),
      description: m['description'] == null ? null : _string(m['description'], 'link', max: 300),
      site: m['site'] == null ? null : _string(m['site'], 'link', max: 60),
      thumb: _thumb(m['thumb']),
    );
  }

  Map<String, Object?> toJson() => {'url': url, 'title': ?title, 'description': ?description, 'site': ?site, 'thumb': ?thumb};
  @override
  bool operator ==(Object other) => other is LinkPreview && _sameJson(toJson(), other.toJson());
  @override
  int get hashCode => jsonEncode(toJson()).hashCode;
}

/// One encrypted file (§3). [key] and [sha256] are unpadded base64url; [size] is plaintext bytes.
class Attachment {
  const Attachment({
    required this.kind,
    required this.blob,
    required this.key,
    required this.sha256,
    required this.mime,
    required this.name,
    required this.size,
    this.width,
    this.height,
    this.duration,
    this.waveform,
    this.thumb,
  });

  final String kind, blob, key, sha256, mime, name;
  final int size;
  final int? width, height;
  final num? duration;
  final List<int>? waveform;
  final String? thumb;

  bool get visual => kind == 'image' || kind == 'video';
  bool get audible => kind == 'audio' || kind == 'voice';

  factory Attachment.fromJson(Object? json) {
    final m = _exact(
      json,
      const {'kind', 'blob', 'key', 'sha256', 'mime', 'name', 'size'},
      const {'width', 'height', 'duration', 'waveform', 'thumb'},
      'attachment',
    );
    final kind = m['kind'], blob = m['blob'], key = m['key'], sha = m['sha256'], mime = m['mime'], size = m['size'];
    if (kind is! String || !attachmentKinds.contains(kind)) _bad('attachment');
    if (blob is! String || !_blobId.hasMatch(blob)) _bad('attachment');
    if (key is! String || !_b64u32.hasMatch(key) || sha is! String || !_b64u32.hasMatch(sha)) _bad('attachment');
    if (mime is! String || mime.length > 128 || !_mime.hasMatch(mime)) _bad('attachment');
    if (size is! int || size < 0 || size > maxAttachmentBytes) _bad('attachment');
    final visual = kind == 'image' || kind == 'video';
    int? dimension(Object? v) {
      if (v == null) return null;
      if (!visual || v is! int || v < 1 || v > 100000) _bad('attachment');
      return v;
    }

    final duration = m['duration'];
    if (duration != null && (!(kind == 'audio' || kind == 'voice' || kind == 'video') || duration is! num || !duration.isFinite || duration < 0 || duration > 86400)) {
      _bad('attachment');
    }
    final waveform = m['waveform'];
    if (waveform != null &&
        (!(kind == 'voice' || kind == 'audio') || waveform is! List || waveform.length > 64 || !waveform.every((v) => v is int && v >= 0 && v <= 31))) {
      _bad('attachment');
    }
    if (m['thumb'] != null && !visual) _bad('attachment');
    return Attachment(
      kind: kind,
      blob: blob,
      key: key,
      sha256: sha,
      mime: mime,
      name: _storedName(_string(m['name'], 'attachment', min: 1, max: 120)),
      size: size,
      width: dimension(m['width']),
      height: dimension(m['height']),
      duration: duration as num?,
      waveform: waveform == null ? null : List<int>.unmodifiable((waveform as List).cast<int>()),
      thumb: _thumb(m['thumb']),
    );
  }

  Map<String, Object?> toJson() => {
    'kind': kind,
    'blob': blob,
    'key': key,
    'sha256': sha256,
    'mime': mime,
    'name': name,
    'size': size,
    'width': ?width,
    'height': ?height,
    'duration': ?duration,
    'waveform': ?waveform,
    'thumb': ?thumb,
  };

  @override
  bool operator ==(Object other) => other is Attachment && _sameJson(toJson(), other.toJson());
  @override
  int get hashCode => jsonEncode(toJson()).hashCode;
}

/// Reactions on one message in a 1:1 chat: who (`me` / `peer`) → their set of emoji.
class Reactions {
  const Reactions([this.byWho = const {}]);
  final Map<String, List<String>> byWho;

  static const maxDistinct = 20;
  static const people = {'me', 'peer'};

  bool get isEmpty => byWho.values.every((v) => v.isEmpty);
  List<String> of(String who) => byWho[who] ?? const [];
  Set<String> get distinct => {for (final list in byWho.values) ...list};

  /// Emoji in first-seen order with their count and whether `me` is among them.
  List<({String emoji, int count, bool mine})> get summary {
    final order = <String>{...of('me'), ...of('peer')}.toList();
    return [for (final e in order) (emoji: e, count: byWho.values.where((v) => v.contains(e)).length, mine: of('me').contains(e))];
  }

  /// Null when nothing changes (already set / not set, or a 21st distinct emoji).
  Reactions? toggle(String who, String emoji, bool on) {
    final mine = of(who);
    if (on == mine.contains(emoji)) return null;
    if (on && !distinct.contains(emoji) && distinct.length >= maxDistinct) return null;
    final next = {for (final e in byWho.entries) e.key: List<String>.of(e.value)};
    final list = next.putIfAbsent(who, () => []);
    on ? list.add(emoji) : list.remove(emoji);
    if (list.isEmpty) next.remove(who);
    return Reactions(next);
  }

  factory Reactions.fromJson(Object? json) {
    if (json is! Map) _bad('reactions');
    final out = <String, List<String>>{};
    for (final entry in json.entries) {
      final list = entry.value;
      if (!people.contains(entry.key) || list is! List || !list.every((e) => e is String && isReactionEmoji(e))) _bad('reactions');
      if (list.isNotEmpty) out[entry.key as String] = List<String>.of(list.cast<String>().toSet());
    }
    final r = Reactions(out);
    if (r.distinct.length > maxDistinct) _bad('reactions');
    return r;
  }

  Map<String, Object?> toJson() => byWho;
}

final _customEmoji = RegExp(r'^:[a-z0-9_+-]{2,32}:$');

/// Extended_Pictographic (approximated by its blocks), regional indicators and the keycap mark.
bool _pictographic(int r) =>
    r == 0xA9 || r == 0xAE || r == 0x203C || r == 0x2049 || r == 0x2122 || r == 0x2139 || r == 0x20E3 ||
    (r >= 0x2194 && r <= 0x21AA) || (r >= 0x231A && r <= 0x23FF) || r == 0x24C2 || (r >= 0x25AA && r <= 0x25FE) ||
    (r >= 0x2600 && r <= 0x27BF) || r == 0x2934 || r == 0x2935 || (r >= 0x2B05 && r <= 0x2B55) ||
    r == 0x3030 || r == 0x303D || r == 0x3297 || r == 0x3299 || (r >= 0x1F000 && r <= 0x1FAFF);

/// One emoji grapheme or `:custom_name:`, at most 40 UTF-8 bytes (same rule as the web client).
bool isReactionEmoji(String value) {
  if (value.isEmpty || utf8.encode(value).length > 40) return false;
  if (_customEmoji.hasMatch(value)) return true;
  return value.characters.length == 1 && value.runes.any(_pictographic);
}
